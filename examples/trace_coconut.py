#!/usr/bin/env python3
"""Trace one 2-of-3 Coconut credential without changing the library."""

import argparse

from coconut.proofs import verify_pi_s, verify_pi_v
from coconut.scheme import (
    agg_cred,
    agg_key,
    blind_sign,
    prepare_blind_sign,
    prove_cred,
    setup,
    ttp_keygen,
    unblind,
    verify_cred,
)
from coconut.utils import ec_sum, elgamal_keygen, lagrange_basis


def parse_args():
    parser = argparse.ArgumentParser(
        description="Trace the original Coconut threshold credential protocol."
    )
    parser.add_argument(
        "--debug-secrets",
        action="store_true",
        help="print secret scalars for local study; never use in production",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    n, threshold, q = 3, 2, 1
    private_m = [42]

    print("[Setup]")
    params = setup(q)
    G, order, g1, hs, g2, pairing = params
    print("groups G1, G2, and GT initialized")
    print("one attribute generator derived in G1")

    print("\n[Key generation]")
    secret_keys, verification_keys = ttp_keygen(params, threshold, n)
    selected_indexes = [1, 2]
    selected_vks = [verification_keys[0], verification_keys[1], None]
    aggregate_vk = agg_key(params, selected_vks)
    print("3 authority key shares generated by TTPKeyGen")
    print("threshold = 2")
    print("verification shares 1 and 2 aggregated")

    print("\n[User]")
    elgamal_private, gamma = elgamal_keygen(params)
    blind_request = prepare_blind_sign(params, gamma, private_m)
    commitment, ciphertexts, issuance_proof = blind_request
    h = G.hashG1(commitment.export())
    assert len(ciphertexts) == 1
    assert verify_pi_s(
        params, gamma, ciphertexts, commitment, issuance_proof
    )
    print("private attribute created")
    print("commitment cm created")
    print("h = H(cm) derived in G1")
    print("one ElGamal ciphertext created")
    print("issuance NIZK created and locally verified")

    blinded_shares = []
    credential_shares = []
    for authority_position in range(threshold):
        authority_number = authority_position + 1
        print("\n[Authority {}]".format(authority_number))
        assert verify_pi_s(
            params, gamma, ciphertexts, commitment, issuance_proof
        )
        print("issuance proof verified")
        blinded_share = blind_sign(
            params,
            secret_keys[authority_position],
            gamma,
            blind_request,
        )
        blinded_shares.append(blinded_share)
        print("blind partial credential issued")

        share = unblind(params, blinded_share, elgamal_private)
        credential_shares.append(share)
        print("user removed the ElGamal blinding factor")

        xi, yis = secret_keys[authority_position]
        share_h, share_s = share
        assert share_h == h
        assert share_s == (xi + yis[0] * private_m[0]) * h
        print("partial credential equation asserted")

    print("\n[Aggregation]")
    ordered_shares = [credential_shares[0], credential_shares[1], None]
    sigma = agg_cred(params, ordered_shares)
    lagrange = lagrange_basis(selected_indexes, order)
    expected_s = ec_sum(
        [
            lagrange[i] * credential_shares[i][1]
            for i in range(threshold)
        ]
    )
    assert sigma[1] == expected_s

    reconstructed_x = sum(
        lagrange[i] * secret_keys[i][0] for i in range(threshold)
    ) % order
    reconstructed_y = sum(
        lagrange[i] * secret_keys[i][1][0] for i in range(threshold)
    ) % order
    assert sigma[1] == (
        reconstructed_x + reconstructed_y * private_m[0]
    ) * sigma[0]
    print("2 valid shares aggregated with Lagrange coefficients")
    print("consolidated credential equation asserted")

    _, alpha, beta = aggregate_vk
    assert pairing(
        sigma[0], alpha + private_m[0] * beta[0]
    ) == pairing(sigma[1], g2)

    print("\n[Showing]")
    theta = prove_cred(params, aggregate_vk, sigma, private_m)
    kappa, nu, sigma_prime, showing_proof = theta
    h_prime, s_prime = sigma_prime
    assert sigma_prime != sigma
    assert pairing(
        h_prime, alpha + private_m[0] * beta[0]
    ) == pairing(s_prime, g2)
    assert verify_pi_v(
        params,
        aggregate_vk,
        sigma_prime,
        kappa,
        nu,
        showing_proof,
    )
    print("credential randomized")
    print("randomized credential still satisfies its signature pairing")
    print("showing NIZK generated and locally verified")

    print("\n[Verification]")
    assert pairing(h_prime, kappa) == pairing(s_prime + nu, g2)
    accepted = verify_cred(params, aggregate_vk, theta)
    assert accepted
    print("pairing equation asserted")
    print("credential accepted = {}".format(accepted))

    if args.debug_secrets:
        print("\n[DEBUG SECRETS — NEVER USE IN PRODUCTION]")
        print("private attribute m = {}".format(private_m[0]))
        print("user ElGamal secret d = {}".format(elgamal_private))
        for i in range(threshold):
            xi, yis = secret_keys[i]
            print(
                "authority {}: xi = {}, yi = {}".format(
                    i + 1, xi, yis[0]
                )
            )
        print("Lagrange coefficients = {}".format(lagrange))
        print("reconstructed x = {}".format(reconstructed_x))
        print("reconstructed y = {}".format(reconstructed_y))


if __name__ == "__main__":
    main()
